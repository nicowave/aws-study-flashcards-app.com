// Builds src/data/readiness.js: 10 questions per certification for the
// homepage's "Am I ready?" check, taken from each game's own question bank and
// split across exam domains by their weight. Rerun after big content changes:
//   node scripts/build-readiness.mjs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/data/readiness.js', import.meta.url));
const PER_CHECK = 10;

const CERTS = [
  { id: 'cloud-practitioner', app: 'aws-cloud-practitioner-game' },
  { id: 'ai-practitioner', app: 'aws-ai-study-game' },
  { id: 'solutions-architect-associate', app: 'aws-saa-study-game' },
  { id: 'developer-associate', app: 'aws-dva-study-game' },
];

const loadDomains = async (app) => {
  const res = await build({
    entryPoints: [`${ROOT}${app}/src/data/index.js`],
    bundle: true, write: false, format: 'esm', platform: 'neutral', logLevel: 'error',
  });
  const url = `data:text/javascript;base64,${Buffer.from(res.outputFiles[0].text).toString('base64')}`;
  return (await import(url)).domains;
};

// Largest-remainder split of PER_CHECK by domain weight, at least 1 each
const split = (domains) => {
  const weights = domains.map((d) => parseFloat(d.weight) || 1);
  const sum = weights.reduce((a, b) => a + b, 0);
  const raw = weights.map((w) => (w / sum) * PER_CHECK);
  const counts = raw.map((r) => Math.max(1, Math.floor(r)));
  while (counts.reduce((a, b) => a + b, 0) < PER_CHECK) {
    const i = raw.map((r, j) => r - counts[j]).reduce((best, v, j, arr) => (v > arr[best] ? j : best), 0);
    counts[i] += 1;
    raw[i] = counts[i]; // don't pick the same domain twice in a row
  }
  return counts;
};

const out = {};
for (const { id, app } of CERTS) {
  const domains = await loadDomains(app);
  const counts = split(domains);
  const questions = [];
  domains.forEach((d, i) => {
    const pool = d.questions.filter((q) => Number.isInteger(q.correctAnswer ?? q.correct) && q.options?.length >= 3);
    const step = pool.length / counts[i];
    for (let k = 0; k < counts[i]; k++) {
      // Spread picks through the domain, skipping its first (free) questions
      const q = pool[Math.min(pool.length - 1, Math.floor(step * k + step / 2))];
      questions.push({
        id: q.id,
        domain: d.name,
        question: q.question,
        options: q.options,
        answer: q.correctAnswer ?? q.correct,
        explanation: q.explanation,
      });
    }
  });
  out[id] = questions;
  console.log(id, counts.join('+'), '=', questions.length);
}

writeFileSync(
  OUT,
  `// Generated by scripts/build-readiness.mjs from each game's question bank. Don't edit by hand.\n` +
    `export const READINESS_QUESTIONS = ${JSON.stringify(out, null, 2)};\n`
);
